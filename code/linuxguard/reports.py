"""Template-based incident reports (Phase 8): the standard mode and the AI-mode fallback.

Built with plain Python (one template; Jinja2 is a declared dependency but unneeded for a
single report). Works for both rule and ML alerts, and never requires any AI to run.
"""

from linuxguard.storage import EvidenceStore

_NEXT_STEPS = {
    "rule": ["Confirm whether the triggering action was authorised (change ticket, operator on console).",
             "Check the acting user, pid and parent process against expected activity for that host.",
             "If unexpected, isolate the host and preserve the raw audit evidence below."],
    "ml": ["Treat this as *unusual*, not confirmed malicious: review the contributing features.",
           "Compare the window against the user's normal activity before escalating.",
           "If benign, note it so the baseline can be improved; if not, pivot to the related events."],
}


def _fmt_event(event, *, mark):
    flag = " **[evidence]**" if mark and event.get("is_evidence") else ""
    who = event.get("user") or event.get("uid")
    bits = [f"`{event['ts']}`", event.get("event_type", "?"), f"exe={event.get('exe')}",
            f"user={who}", f"pid={event.get('pid')}"]
    if event.get("path"):
        bits.append(f"path={event['path']}")
    if event.get("src_ip"):
        bits.append(f"src={event['src_ip']}")
    return "- " + " ".join(str(b) for b in bits) + flag


def incident_markdown(store: EvidenceStore, alert_id, *, related_minutes=5) -> str:
    """Render a Markdown incident report for one alert, with its correlated timeline."""
    alert = store.get_alert(alert_id)
    if alert is None:
        raise ValueError(f"no alert with id {alert_id}")
    evidence = store.timeline(alert_id)
    related = store.related_events(alert_id, minutes=related_minutes)
    origin = "Rule " + alert["rule_id"] if alert["source"] == "rule" else "ML anomaly detector"
    lines = [
        f"# Incident report: {alert['title']}",
        "",
        f"- **Alert id:** {alert_id}",
        f"- **Detected:** {alert['ts']}",
        f"- **Source:** {alert['source']} ({origin})",
        f"- **Severity:** {alert['severity']}",
        f"- **Status:** {alert['status']}",
    ]
    if alert["source"] == "ml" and alert["anomaly_score"] is not None:
        lines.append(f"- **Anomaly score:** {alert['anomaly_score']:.4f} "
                     f"(window {alert['window_start']} .. {alert['window_end']})")
    lines += ["", "## Why this fired", "", alert["reason"], "",
              f"## Timeline (related activity within +/-{related_minutes} min, evidence marked)", ""]
    lines += [_fmt_event(event, mark=True) for event in related] or ["- (no correlated events)"]
    lines += ["", "## Raw audit evidence", ""]
    for event in evidence:
        lines.append(f"### audit {event.get('audit_id')} (event id {event['id']})")
        lines.append("```")
        lines.append(event["raw"].rstrip("\n"))
        lines.append("```")
    lines += ["", "## Suggested next steps", ""]
    lines += [f"{i}. {step}" for i, step in enumerate(_NEXT_STEPS[alert["source"]], 1)]
    lines += ["", "_Generated by LinuxGuard (standard template mode; no AI was used)._"]
    return "\n".join(lines) + "\n"
